    // =========================
    // POPULATE MEMBER TYPES
    // =========================
    private void populateMemberTypes() {
        try {
            Connection con = Database.getConnection();
            String sql = "SELECT DISTINCT type FROM ledgers ORDER BY type";
            PreparedStatement ps = con.prepareStatement(sql);
            ResultSet rs = ps.executeQuery();

            selectTypeField.removeAllItems();

            while (rs.next()) {
                selectTypeField.addItem(rs.getString("type"));
            }

            rs.close();
            ps.close();
            con.close();
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    // =========================
    // SAVE LEDGER
    // =========================
    private void saveLedger() {
        String desc = description.getText().trim();
        String type = (String) selectTypeField.getSelectedItem();
        Date date = ledgerDate.getDate();

        if (desc.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a description", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (type == null || type.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a type", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (date == null) {
            JOptionPane.showMessageDialog(this, "Please select a date", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            Connection con = Database.getConnection();
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            String dateStr = sdf.format(date);

            String sql;
            if (ledgerId == -1) {
                sql = "INSERT INTO ledgers (description, type, date) VALUES (?, ?, ?)";
            } else {
                sql = "UPDATE ledgers SET description = ?, type = ?, date = ? WHERE id = ?";
            }
            
            PreparedStatement ps = con.prepareStatement(sql);
            ps.setString(1, desc);
            ps.setString(2, type);
            ps.setString(3, dateStr);
            if (ledgerId != -1) {
                ps.setInt(4, ledgerId);
            }

            ps.executeUpdate();

            ps.close();
            con.close();

            JOptionPane.showMessageDialog(this, "Ledger " + (ledgerId == -1 ? "added" : "updated") + " successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);

            // Clear form
            description.setText("");
            ledgerDate.setDate(null);

            if (callback != null) {
                callback.run();
            }

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error saving ledger: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }


